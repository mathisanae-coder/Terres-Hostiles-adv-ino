// Génère th_data.h depuis le moteur JS (index.html) : cartes, environnements, météo, saisons, recettes, difficultés.
const T=require('./dump_data.js');
const slug=s=>s.normalize('NFD').replace(/[̀-ͯ]/g,'').replace(/[^A-Za-z0-9]+/g,'_').replace(/^_|_$/g,'').toUpperCase();
const S=s=>JSON.stringify(String(s));
const ENVIDS=T.ENVS.map(e=>e.id);
const remOut=new Set(T.REMEDES.map(r=>r.out));
const KINDS=['mat','objet','food','soin','contre','habitat','pred','proie','malus','chance'];
let defs=T.DEFS.filter(d=>KINDS.includes(d.k)&&!remOut.has(d.nom)&&!(d.eff&&d.eff.recette)&&d.nom!=='Parchemin de recettes');
const idx=new Map(defs.map((d,i)=>[d.nom,i]));
const TAGS=[];defs.forEach(d=>[...(d.tags||[]),...(d.req||[]),...(d.repel||[]),...(d.catch||[]),...(d.counter||[])].forEach(x=>{if(!TAGS.includes(x))TAGS.push(x)}));
['abri','solide','feu','foyer'].forEach(x=>{if(!TAGS.includes(x))TAGS.push(x)});
const tm=a=>{let m=0;(a||[]).forEach(x=>{m|=(1<<TAGS.indexOf(x))});return m>>>0};
const bm=a=>a?a.reduce((m,e)=>m|(1<<ENVIDS.indexOf(e)),0):0x7FF;
const ref=n=>n&&idx.has(n)?idx.get(n):-1;
const CONDS=['saignement','infection','fracture','gastro'];
const cm=a=>(a||[]).reduce((m,c)=>m|(1<<CONDS.indexOf(c)),0);
const STRESS={chaud:0,froid:1,humide:2};
let o=[];
o.push('/* ===== DONNÉES GÉNÉRÉES depuis index.html (gen_data.js) — ne pas modifier à la main ===== */');
o.push(`#define N_ENV ${T.ENVS.length}\n#define N_DEF ${defs.length}\n#define N_WX ${Object.keys(T.WX).length}\n#define SEASON_LEN ${T.SEASON_LEN}\n#define HAND_MAX ${T.HAND_MAX}\n#define INV_MAX ${T.INV_MAX}\n#define SAT_MAX ${T.SAT_MAX}\n#define EAU_MAX ${T.EAU_MAX}\n#define ENE_MAX ${T.ENE_MAX}\n#define AP_BASE ${T.AP_BASE}\n#define EXPLORE_DRAWS ${T.EXPLORE_DRAWS}\n#define SIGNAL_GOAL ${T.SIGNAL_GOAL}`);
o.push('enum { '+TAGS.map((t,i)=>`T_${slug(t)}=${(1<<i)>>>0}u`).join(', ')+' };');
o.push('enum { '+KINDS.map((k,i)=>`K_${k.toUpperCase()}=${i}`).join(', ')+' };');
o.push('enum { '+ENVIDS.map((e,i)=>`E_${e.toUpperCase()}=${i}`).join(', ')+' };');
o.push('enum { '+CONDS.map((c,i)=>`CD_${c.toUpperCase()}=${1<<i}`).join(', ')+' };');
const WXK=Object.keys(T.WX);
o.push('enum { '+WXK.map((w,i)=>`W_${w.toUpperCase()}=${i}`).join(', ')+' };');
o.push('enum { '+defs.map((d,i)=>`D_${slug(d.nom)}=${i}`).join(', ')+' };');
o.push(`struct CardDef{const char*nom;const char*txt;uint8_t k,n,dur,perish,power,lvl,need,cost,lootN,burn,passif;uint16_t biomes;uint32_t tags,req,link;int16_t dry,loot,extra,gain0,gain1;int8_t atk,def,sat,eau,pv,ene,moral,r0,r1,r2;uint8_t cure,cond,lose;};`);
o.push('static const CardDef DEFS[N_DEF]={');
defs.forEach(d=>{
  const e=d.eff||{},res=d.res||{};
  const link=tm(d.k==='pred'?d.repel:d.k==='proie'?d.catch:d.k==='malus'?d.counter:[]);
  const gain=(e.gain||[]).map(ref);
  const lose={hand:1,food:2,equip:3}[e.lose]||0;
  const pas={citerne:1,jardin:2}[d.passif]||0;
  const f=[S(d.nom),S(d.txt||''),'K_'+d.k.toUpperCase(),d.n||0,d.dur||0,d.perish||0,d.power||0,d.lvl||0,d.need||0,d.cost||0,d.lootN||0,d.burn?1:0,pas,
    '0x'+bm(d.biomes).toString(16),tm(d.tags)+'u',tm(d.req)+'u',link+'u',ref(d.dry),ref(d.loot),ref(d.extra),gain[0]!==undefined?gain[0]:-1,gain[1]!==undefined?gain[1]:-1,
    d.atk||0,d.def||0,d.sat||e.sat||0,d.eau||e.eau||0,d.pv||e.pv||0,d.ene||e.ene||0,d.moral||e.moral||0,res.chaud||0,res.froid||0,res.humide||0,cm(d.cure),e.cond?CONDS.indexOf(e.cond)>=0?(1<<CONDS.indexOf(e.cond)):0:0,lose];
  o.push(' {'+f.join(',')+'},');
});
o.push('};');
// chance/malus : les effets pv/ene/eau sont dans pv/ene/eau (déjà fusionnés ci-dessus)
o.push(`struct EnvDef{const char*nom;const char*desc;uint8_t stress,niv,faim,soif;int16_t kit;uint8_t yB,yP,yF,forP,nForage;int16_t forage[3];uint16_t color;};`);
o.push('static const EnvDef ENVS[N_ENV]={');
const col565=h=>{const r=parseInt(h.slice(1,3),16),g=parseInt(h.slice(3,5),16),b=parseInt(h.slice(5,7),16);return '0x'+(((r>>3)<<11)|((g>>2)<<5)|(b>>3)).toString(16)};
T.ENVS.forEach(e=>{
  const fl=e.forage.list.map(ref);while(fl.length<3)fl.push(-1);
  o.push(` {${S(e.nom)},${S(e.desc)},${STRESS[e.stress]},${e.niv},${e.faim},${e.soif},${ref(e.kit)},${e.yield.Bois},${e.yield.Pierre},${e.yield.Fibres},${Math.round(e.forage.p*100)},${e.forage.list.length},{${fl.join(',')}},${col565(e.tint)}},`);
});
o.push('};');
o.push(`struct WxDef{const char*nom;const char*txt;int8_t st,eau,ap,expl,rain;};`);
o.push('static const WxDef WXS[N_WX]={');
WXK.forEach(k=>{const w=T.WX[k];o.push(` {${S(w.nom)},${S(w.txt)},${w.st},${w.eau},${w.ap},${w.expl},${w.rain?1:0}},`)});
o.push('};');
o.push('static const uint8_t WX_TABLE[N_ENV][8]={');
ENVIDS.forEach(e=>o.push(' {'+T.WX_TABLE[e].map(w=>WXK.indexOf(w)).join(',')+'},'));
o.push('};');
o.push('struct SeasonFx{int8_t st,eau,food;const char*txt;};');
o.push('static const SeasonFx SEASON_FX[N_ENV][4]={');
ENVIDS.forEach(e=>o.push(' {'+T.SEASON_FX[e].map(s=>`{${s.st},${s.eau},${s.food},${S(s.txt)}}`).join(',')+'},'));
o.push('};');
o.push('static const char*const SEASON_NAME[4]={'+T.SEASONS.map(S).join(',')+'};');
o.push('static const char*const HAB_NAME[4]={'+T.HAB_NAMES.map(S).join(',')+'};');
o.push('static const char*const STRESS_NAME[3]={"Chaleur","Froid","Humidité"};');
o.push('static const char*const COND_NAME[4]={'+CONDS.map(c=>S(T.COND_LABEL[c])).join(',')+'};');
o.push('static const char*const COND_TXT[4]={'+CONDS.map(c=>S(T.COND_TXT[c])).join(',')+'};');
o.push('static const uint8_t COND_DAYS[4]={'+CONDS.map(c=>T.COND_DAYS[c]).join(',')+'};');
o.push('static const uint8_t RAW_RISK[N_ENV]={'+ENVIDS.map(e=>T.RAW_RISK[e]||0).join(',')+'};');
o.push('static const char*const CARRIER[N_ENV]={'+ENVIDS.map(e=>S(T.CARRIERS[e]||'avion')).join(',')+'};');
const DK=Object.keys(T.DIFF);
o.push('struct DiffDef{const char*nom;const char*txt;int8_t ap,st,pv,drain,pw,loc,start;uint8_t chance100;uint8_t wear100;};');
o.push('#define N_DIFF '+DK.length);o.push('static const DiffDef DIFFS[N_DIFF]={');
DK.forEach(k=>{const d=T.DIFF[k];o.push(` {${S(d.nom)},${S(d.txt)},${d.ap},${d.st},${d.pv},${d.drain},${d.pw},${d.loc},${d.start},${Math.round(d.chance*100)},${Math.round(d.wear*100)}},`)});
o.push('};');
const rec=T.RECIPES.filter(r=>idx.has(r.out));
o.push(`struct Recipe{int16_t out;uint8_t bois,pierre,fibres,peau;uint32_t tools;uint16_t notEnv;};`);
o.push(`#define N_REC ${rec.length}`);
o.push('static const Recipe RECIPES[N_REC]={');
rec.forEach(r=>o.push(` {${idx.get(r.out)},${r.mats.Bois||0},${r.mats.Pierre||0},${r.mats.Fibres||0},${r.mats.Peau||0},${tm(r.tools)}u,0x${bm(r.not).toString(16).replace(/^7ff$/,'0')}},`));
o.push('};');
require('fs').writeFileSync('th_data.h',o.join('\n')+'\n');
console.log('defs',defs.length,'tags',TAGS.length,'recettes',rec.length,'octets',o.join('\n').length);
console.log('exclus:',T.DEFS.filter(d=>!idx.has(d.nom)).map(d=>d.nom).join(', '));
